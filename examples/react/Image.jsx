import React from 'react';

/**
 * Reusable React Image Component for Atihsrah-signed assets.
 *
 * ARCHITECTURAL REQUIREMENTS:
 * 1. NEVER import signing keys or perform HMAC operations inside client-side components.
 *    Any secret key shipped in a browser bundle is permanently compromised.
 * 2. NEVER append query parameters (e.g. `url + '&w=' + width`) in client-side code.
 *    Atihsrah verifies the HMAC signature over all query parameters; modifying or
 *    adding parameters in transit triggers a signature mismatch (HTTP 401).
 * 3. Responsive images must receive pre-signed `srcSet` generated by your server.
 * 4. Pass `loading="eager"` (or priority={true}) for the page Hero image to prevent
 *    LCP regressions, and `loading="lazy"` for all below-the-fold elements.
 */
export function ResponsiveImage({
  src,
  srcSet,
  sizes = '100vw',
  alt,
  width,
  height,
  loading = 'lazy',
  className = '',
  style = {},
  onLoad,
}) {
  return (
    <img
      src={src}
      srcSet={srcSet}
      sizes={sizes}
      alt={alt}
      width={width}
      height={height}
      loading={loading}
      decoding={loading === 'eager' ? 'sync' : 'async'}
      className={className}
      style={{
        maxWidth: '100%',
        height: 'auto',
        objectFit: 'cover',
        ...style,
      }}
      onLoad={onLoad}
    />
  );
}

export default ResponsiveImage;

